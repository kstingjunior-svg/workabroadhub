// 2026-11-27 (Tony, permanent): no CV or document a customer receives may show
// it came from WorkAbroad Hub: no footer/watermark text, no brand in the file
// properties, no brand in the download file name, no brand in share messages.
import { describe, it, expect } from "vitest";
import fs from "fs";
import path from "path";
import { neutralDocName } from "../../client/src/lib/doc-filename";
import { stripBrandLines } from "../../server/services/document-renderer";

const ROOT = path.resolve(__dirname, "../..");
const read = (p: string) => fs.readFileSync(path.join(ROOT, p), "utf8");

function walk(dir: string, out: string[] = []): string[] {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== "node_modules") walk(rel, out); }
    else if (/\.(ts|tsx)$/.test(e.name)) out.push(rel);
  }
  return out;
}
const SOURCES = [...walk("server"), ...walk("client/src"), ...walk("shared")];

describe("customer documents carry no WorkAbroad Hub mark", () => {
  it("no 'Generated by WorkAbroad' text anywhere in the app", () => {
    // verified-profile is a credential page whose whole point is saying who
    // verified it; it is not a CV or letter the customer submits.
    const ALLOW = new Set([path.join("client/src/pages/verified-profile.tsx")]);
    const hits = SOURCES.filter((f) => !ALLOW.has(f) && /Generated by\s*(<[^>]+>)?\s*WorkAbroad/i.test(read(f)));
    expect(hits).toEqual([]);
  });

  it("no download file names that start with or contain the brand", () => {
    const re = /`workabroadhub-\$\{|_WorkAbroadHub\.|-workabroadhub\.|filename="WorkAbroad_/;
    const hits = SOURCES.filter((f) => re.test(read(f)));
    expect(hits).toEqual([]);
  });

  it("renderer writes no footer and neutral file properties", () => {
    const src = read("server/services/document-renderer.ts");
    expect(src).not.toMatch(/new Footer\(/);
    expect(src).not.toMatch(/creator:\s*"[^"]+"/);
    expect(src).not.toMatch(/(Author|Creator|Producer):\s*"[^"]+"/);
  });

  it("no route passes a footer to the renderer", () => {
    const hits = SOURCES.filter((f) => f.startsWith("server") && /footer:\s*["'`][^"'`]*WorkAbroad/i.test(read(f)));
    expect(hits).toEqual([]);
  });

  it("neutral names", () => {
    expect(neutralDocName("cv_fix_lite", "pdf")).toBe("CV.pdf");
    expect(neutralDocName("cover_letter", "docx")).toBe("Cover_Letter.docx");
    expect(neutralDocName("sop", ".pdf")).toBe("Statement_of_Purpose.pdf");
    expect(neutralDocName(undefined, "pdf")).toBe("Document.pdf");
  });

  it("strips any brand credit line the AI might write", () => {
    const body = "Jane Doe\nNurse, 5 years\n\nGenerated by WorkAbroad Hub — workabroadhub.tech\n_Prepared by WorkAbroad Hub · 27 Nov 2026_\nhttps://workabroadhub.tech\nReferences available";
    expect(stripBrandLines(body)).toBe("Jane Doe\nNurse, 5 years\n\nReferences available");
    // A real sentence mentioning travel/abroad is kept
    expect(stripBrandLines("I want to work abroad in Canada")).toBe("I want to work abroad in Canada");
  });
});
